/** Guest API — the only place guest endpoints are called.
 *
 * Every function goes through the shared client (no second client).
 * Guest auth is the raw QR token in the `X-Table-Token` header
 * (api-plan.md § 1), except session-open which takes it in the path
 * (api-plan.md § 3). The backend does not exist for these endpoints
 * yet (Stage 3) — callers must handle ApiError and show the
 * not-connected state; nothing here fakes a success.
 */
import { api } from "@/shared/api/client";
import { HELP_CALL_LABELS } from "@/shared/api/types";
import type {
  Bill,
  BillSplitRequest,
  GuestMenuResponse,
  GuestSessionResponse,
  HelpCall,
  HelpCallRequest,
  Order,
  OrderPlacementRequest,
  OrderPlacementResponse,
  Receipt,
  ReviewRequest,
} from "@/shared/api/types";

const V1 = "/api/v1";

function tableHeaders(tableToken: string): { "X-Table-Token": string } {
  return { "X-Table-Token": tableToken };
}

/** Session open — validates the token, creates/resumes the session
 * (api-plan.md § 3: GET /guest/t/:tableToken). */
export function fetchGuestSession(tableToken: string) {
  return api.get<GuestSessionResponse>(
    `${V1}/guest/t/${encodeURIComponent(tableToken)}`,
  );
}

/** Current session (api-plan.md § 3: GET /guest/session). */
export function fetchGuestSessionCurrent(tableToken: string) {
  return api.get<GuestSessionResponse>(`${V1}/guest/session`, {
    headers: tableHeaders(tableToken),
  });
}

/** Full menu for this restaurant (api-plan.md § 3: GET /guest/menu). */
export function fetchGuestMenu(tableToken: string) {
  return api.get<GuestMenuResponse>(`${V1}/guest/menu`, {
    headers: tableHeaders(tableToken),
  });
}

/** Order placement (api-plan.md § 4.1). The request carries no prices;
 * the backend recomputes them. The idempotency key is generated by
 * the caller (one per placement attempt) and reused on retry. */
export function placeOrder(
  tableToken: string,
  request: OrderPlacementRequest,
  idempotencyKey: string,
) {
  return api.post<OrderPlacementResponse>(`${V1}/orders`, request, {
    headers: { ...tableHeaders(tableToken), "Idempotency-Key": idempotencyKey },
  });
}

/** Orders for this session (api-plan.md § 4.2: GET /guest/orders). */
export function fetchGuestOrders(tableToken: string) {
  return api.get<{ data: Order[] }>(`${V1}/guest/orders`, {
    headers: tableHeaders(tableToken),
  });
}

/** One order of this session, for live tracking (GET /guest/orders/:id). */
export function fetchGuestOrder(tableToken: string, orderId: string) {
  return api.get<{ data: Order }>(
    `${V1}/guest/orders/${encodeURIComponent(orderId)}`,
    { headers: tableHeaders(tableToken) },
  );
}

/** Cancel an order (api-plan.md § 4.2: POST /orders/:id/cancel).
 * Guest cancellation window is decision D8, undecided — the backend
 * enforces it; the UI only offers cancel before `accepted`. */
export function cancelOrder(tableToken: string, orderId: string, reason?: string) {
  return api.post<{ data: Order }>(
    `${V1}/orders/${encodeURIComponent(orderId)}/cancel`,
    { reason },
    { headers: tableHeaders(tableToken) },
  );
}

/** Help call (api-plan.md § 5: POST /guest/help-calls). The body
 * carries the type label in `note` as well as the `type` field, so
 * nothing is lost if the Stage 3 backend only reads `note` today. */
export function requestHelpCall(tableToken: string, request: HelpCallRequest) {
  const label = HELP_CALL_LABELS[request.type];
  const note = request.note ? `${label} — ${request.note}` : label;
  return api.post<{ data: HelpCall }>(
    `${V1}/guest/help-calls`,
    { type: request.type, note },
    { headers: tableHeaders(tableToken) },
  );
}

/** The session's open bill (api-plan.md § 7.1 as built in Stage 6:
 * GET /guest/bill). 404 when no bill exists yet. */
export function fetchGuestBill(tableToken: string) {
  return api.get<{ data: Bill }>(`${V1}/guest/bill`, {
    headers: tableHeaders(tableToken),
  });
}

/** Generate (or retrieve/regenerate) the bill from the session's
 * unpaid orders (Stage 6: POST /guest/bill). One open bill per
 * session — a repeat call returns the same bill, never a duplicate. */
export function requestBill(tableToken: string) {
  return api.post<{ data: Bill }>(`${V1}/guest/bill`, {}, {
    headers: tableHeaders(tableToken),
  });
}

/** Guest taps "Pay by Cash" — requests payment, creates NO payment
 * (Stage 6: PATCH /guest/bill/request-payment). Only staff can
 * confirm cash collection (POST /staff/bills/:id/payments). */
export function requestCashPayment(tableToken: string) {
  return api.patch<{ data: Bill }>(
    `${V1}/guest/bill/request-payment`,
    {},
    { headers: tableHeaders(tableToken) },
  );
}

/** Split a bill (Stage 6: POST /guest/bill/splits). Validated
 * server-side: equal parts >= 2, custom amounts summing exactly to
 * the total. */
export function createBillSplit(
  tableToken: string,
  split: BillSplitRequest,
) {
  return api.post<{ data: Bill }>(
    `${V1}/guest/bill/splits`,
    split,
    { headers: tableHeaders(tableToken) },
  );
}

/** Receipt data (Stage 6: GET /guest/bill/receipt). Only after the
 * bill is paid — otherwise a 409. */
export function fetchGuestReceipt(tableToken: string) {
  return api.get<{ data: Receipt }>(`${V1}/guest/bill/receipt`, {
    headers: tableHeaders(tableToken),
  });
}

/** Review after the bill is paid (api-plan.md § 8: POST /guest/reviews). */
export function submitReview(tableToken: string, review: ReviewRequest) {
  return api.post<{ data: { id: string } }>(`${V1}/guest/reviews`, review, {
    headers: tableHeaders(tableToken),
  });
}
